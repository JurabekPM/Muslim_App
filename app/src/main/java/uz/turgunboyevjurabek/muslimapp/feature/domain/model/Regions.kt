        private val bySlug = supported.associateBy(Regions::slug)
        private val defaultRegion = bySlug.getValue("fargona-shahri")

        fun resolve(savedRegion: String?): Regions =
            bySlug[savedRegion] ?: bySlug[legacySlugs[savedRegion]] ?: defaultRegion

        fun search(query: String, kind: RegionKind? = null): List<Regions> {
            val candidates = if (kind == null) supported else supported.filter { it.kind == kind }
            val normalized = normalizeRegionQuery(query).trim()
            if (normalized.isEmpty()) return candidates

            val terms = normalized.split(whitespace)
            val matches = candidates.filter { region ->
                terms.all { it in region.searchName || it in region.searchSlug }
            }
            return matches.sortedBy { !it.searchName.startsWith(normalized) }
        }
    }
